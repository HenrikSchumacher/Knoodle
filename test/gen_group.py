#!/usr/bin/env python3
"""gen_group -- write the one source file that a GROUP of tests is built from.

    ./gen_group.py <group> <out.cpp>     # members come from manifest.tsv, column 9
    ./gen_group.py --members=a,b <out.cpp>

WHY GROUPS EXIST. Knoodle, Tensors and Tools are header-only, so every test
driver used to recompile the whole stack by itself: 45 drivers, 408 CPU-seconds,
of which the tests then RAN for 24. Most of a driver's compile is the same
template instantiations as its neighbour's. Compiled as one translation unit
those are made once: five small drivers took 8.2 s together against 25.7 s
apart (measured 2026-11-12). A group is that one translation unit.

WHAT A GROUP IS. One binary, build/group_<name>, holding every member's main().
The runner calls it as

    build/group_<name> <test> [the test's own arguments...]

and exactly one member's main() runs, in its own process, with argv[0] set to
the test's name. A test still passes or fails by itself, has its own log and
its own row in the manifest; only the build is shared.

HOW THE FILE IS BUILT. Every member is #included inside its own namespace, so
two tests may both have a `check()` or a `failures` at file scope. For that to
work the headers the members name must NOT land inside those namespaces, so
their #include lines are hoisted to the top of the file, where they are read
once at global scope; when a member then names the same header, its include
guard makes that a no-op.

WHAT CANNOT BE GROUPED, and fails to compile if it is (loudly, at build time):

  * a test that reopens `namespace Knoodle` or `namespace std`, or specializes
    a template from one of them -- inside the member's namespace that names a
    different thing;
  * a test that #defines something before a header to configure it -- the
    header has already been read by then;
  * a test whose #include sits inside an #if. gen_group refuses these itself.

Leave such a test's group column at '-': it is then built alone, as before.
`make <test>` builds any test alone, grouped or not, which is how to debug one.

The file is rewritten only when its contents change, so touching an unrelated
manifest row does not rebuild a group.
"""

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MANIFEST = os.path.join(HERE, "manifest.tsv")

INCLUDE = re.compile(r'^\s*#\s*include\s*([<"][^>"]+[>"])')
CONDITIONAL = re.compile(r'^\s*#\s*(if|ifdef|ifndef|endif)\b')


def members_of(group):
    """[(target, source)] for the rows whose group column is `group`, in order."""
    out = []
    with open(MANIFEST) as f:
        for line in f:
            if line.startswith("#") or not line.strip():
                continue
            cols = line.rstrip("\n").split("\t")
            if len(cols) >= 9 and cols[8] == group:
                out.append((cols[0], cols[0] + ".cpp" if cols[3] == "-" else cols[3]))
    return out


def includes_of(source):
    """The #include operands of `source`, in order. Refuses one inside an #if."""
    found, depth = [], 0
    with open(os.path.join(HERE, source), errors="replace") as f:
        for lineno, line in enumerate(f, 1):
            m = CONDITIONAL.match(line)
            if m:
                depth += -1 if m.group(1) == "endif" else 1
                continue
            m = INCLUDE.match(line)
            if not m:
                continue
            if depth:
                raise SystemExit(
                    f"gen_group: {source}:{lineno}: #include inside an #if. It cannot "
                    f"be hoisted out of the test's namespace, so this test cannot be "
                    f"in a group. Set its group column to '-'.")
            found.append(m.group(1))
    return found


def generate(group, members):
    hoisted, seen = [], set()
    for _, source in members:
        for inc in includes_of(source):
            if inc not in seen:
                seen.add(inc)
                hoisted.append(inc)

    o = []
    o.append(f"// GENERATED by test/gen_group.py from test/manifest.tsv -- do not edit.")
    o.append(f"// Group '{group}': {len(members)} tests in one translation unit.")
    o.append(f"// See the header of gen_group.py for why and how.")
    o.append("")
    o.append("// Every header any member names, read once, at global scope.")
    o.append("#include <cstdio>")
    o.append("#include <cstring>")
    for inc in hoisted:
        o.append(f"#include {inc}")
    o.append("")
    for target, source in members:
        # `main` is renamed as well as wrapped: a function called main in a
        # namespace is legal, but compilers differ on warning about it.
        o.append(f"namespace group_member_{target} {{")
        o.append(f"#define main test_main")
        o.append(f'#include "{source}"')
        o.append(f"#undef main")
        o.append(f"}}")
        o.append("")
    o.append("namespace {")
    o.append("// A test's main() may or may not take arguments.")
    o.append("[[maybe_unused]] int call(int (*f)(), int, char**) { return f(); }")
    o.append("[[maybe_unused]] int call(int (*f)(int, char**), int argc, char** argv) { return f(argc, argv); }")
    o.append("[[maybe_unused]] int call(int (*f)(int, const char**), int argc, char** argv)")
    o.append("    { return f(argc, const_cast<const char**>(argv)); }")
    o.append("[[maybe_unused]] int call(int (*f)(int, char const* const*), int argc, char** argv)")
    o.append("    { return f(argc, argv); }")
    o.append("}")
    o.append("")
    o.append("int main(int argc, char** argv)")
    o.append("{")
    o.append("    const char* want = argc > 1 ? argv[1] : \"\";")
    for target, _ in members:
        o.append(f'    if (std::strcmp(want, "{target}") == 0)')
        o.append(f"        return call(&group_member_{target}::test_main, argc - 1, argv + 1);")
    names = " ".join(t for t, _ in members)
    o.append(f'    std::fprintf(stderr, "group {group}: no test named \'%s\'. Its tests are:\\n'
             f'  {names}\\n", want);')
    o.append("    return 2;")
    o.append("}")
    return "\n".join(o) + "\n"


def main():
    args = sys.argv[1:]
    if len(args) != 2:
        print(__doc__)
        return 2
    if args[0].startswith("--members="):
        group = "adhoc"
        members = [(t, t + ".cpp") for t in args[0].split("=", 1)[1].split(",")]
    else:
        group = args[0]
        members = members_of(group)
        if not members:
            raise SystemExit(f"gen_group: no manifest row has group '{group}'")

    text = generate(group, members)
    out = args[1]
    try:
        if open(out).read() == text:
            return 0
    except OSError:
        pass
    os.makedirs(os.path.dirname(os.path.abspath(out)), exist_ok=True)
    with open(out, "w") as f:
        f.write(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
